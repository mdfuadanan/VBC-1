library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use std.env.all;

entity tb_VBC1_Board_Top is
end tb_VBC1_Board_Top;

architecture Behavioral of tb_VBC1_Board_Top is

    signal CLK : std_logic := '0';
    signal RST : std_logic := '0';

    signal SW : std_logic_vector(3 downto 0) := "0000";

    signal LED : std_logic_vector(7 downto 0);
    signal Seg : std_logic_vector(6 downto 0);

begin

    ----------------------------------------------------------------
    -- DUT: VBC1_Board_Top
    ----------------------------------------------------------------
    DUT : entity work.VBC1_Board_Top
        port map(
            CLK => CLK,
            RST => RST,
            SW  => SW,
            LED => LED,
            Seg => Seg
        );

    ----------------------------------------------------------------
    -- Clock
    -- Same clock as tb_VBC1_Top
    -- Period = 10 ns
    ----------------------------------------------------------------
    CLK <= not CLK after 5 ns;

    ----------------------------------------------------------------
    -- Stimulus
    -- EXACTLY the same timing and SW sequence as tb_VBC1_Top
    ----------------------------------------------------------------
    process
    begin

        ------------------------------------------------------------
        -- Reset
        ------------------------------------------------------------
        RST <= '1';
        SW  <= "0000";

        wait for 20 ns;

        RST <= '0';

        ------------------------------------------------------------
        -- SW = 0000
        ------------------------------------------------------------
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0001
        ------------------------------------------------------------
        SW <= "0001";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0010
        ------------------------------------------------------------
        SW <= "0010";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0011
        ------------------------------------------------------------
        SW <= "0011";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0100
        ------------------------------------------------------------
        SW <= "0100";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0101
        ------------------------------------------------------------
        SW <= "0101";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0110
        ------------------------------------------------------------
        SW <= "0110";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 0111
        ------------------------------------------------------------
        SW <= "0111";
        wait for 100 ns;

        ------------------------------------------------------------
        -- SW = 1111
        ------------------------------------------------------------
        SW <= "1111";
        wait for 100 ns;

        ------------------------------------------------------------
        -- End simulation
        ------------------------------------------------------------
        report "Simulation finished" severity note;
        stop;

    end process;

end Behavioral;