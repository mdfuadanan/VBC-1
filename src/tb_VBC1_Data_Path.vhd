library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use std.env.all;

entity VBC1_Data_Path_tb is
end VBC1_Data_Path_tb;

architecture Behavioral of VBC1_Data_Path_tb is

    component VBC1_Data_Path
        port(
            M1, M2, M3, M4, M5 : in std_logic;
            load_r0, load_r1, load_op : in std_logic;
            IR : in std_logic_vector(7 downto 0);
            DI : in std_logic_vector(3 downto 0);
            clk : in std_logic;
            rst : in std_logic;
            op : out std_logic_vector(3 downto 0);
            r0 : out std_logic_vector(3 downto 0);
            r1 : out std_logic_vector(3 downto 0)
        );
    end component;

    signal M1, M2, M3, M4, M5 : std_logic := '0';
    signal load_r0, load_r1, load_op : std_logic := '0';

    signal IR : std_logic_vector(7 downto 0) := (others => '0');
    signal DI : std_logic_vector(3 downto 0) := "1000";

    signal clk : std_logic := '0';
    signal rst : std_logic := '0';

    signal op : std_logic_vector(3 downto 0);
    signal r0 : std_logic_vector(3 downto 0);
    signal r1 : std_logic_vector(3 downto 0);

begin

    --------------------------------------------------
    -- DUT
    --------------------------------------------------

    DUT : VBC1_Data_Path
        port map(
            M1       => M1,
            M2       => M2,
            M3       => M3,
            M4       => M4,
            M5       => M5,
            load_r0  => load_r0,
            load_r1  => load_r1,
            load_op  => load_op,
            IR       => IR,
            DI       => DI,
            clk      => clk,
            rst      => rst,
            op       => op,
            r0       => r0,
            r1       => r1
        );

    --------------------------------------------------
    -- CLOCK
    -- 10 ns period
    --------------------------------------------------

    clk <= not clk after 5 ns;

    --------------------------------------------------
    -- TEST PROCESS
    --------------------------------------------------

    process
    begin

        --------------------------------------------------
        -- RESET
        --------------------------------------------------

        rst <= '1';

        wait for 20 ns;

        rst <= '0';

        wait for 10 ns;


        --------------------------------------------------
        -- B0
        -- M1 = 1
        -- load_r1 = 1
        --------------------------------------------------

        IR <= "10110000";

        M1 <= '1';
        load_r1 <= '1';

        wait for 10 ns;

        M1 <= '0';
        load_r1 <= '0';

        wait for 10 ns;


        --------------------------------------------------
        -- D0
        -- M2 = 1
        -- load_op = 1
        --------------------------------------------------

        IR <= "11010000";

        M2 <= '1';
        load_op <= '1';

        wait for 10 ns;

        M2 <= '0';
        load_op <= '0';

        wait for 10 ns;


        --------------------------------------------------
        -- 23
        -- M3 = 1
        -- load_r0 = 1
        --------------------------------------------------

        IR <= "00100011";

        M3 <= '1';
        M5 <='1';
        load_r0 <= '1';

        wait for 10 ns;
        
        M3 <= '0';
        M5 <= '0';
        load_r0 <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- C0
        -- load_op = 1
        --------------------------------------------------

        IR <= "11000000";
        load_op <= '1';

        wait for 10 ns;

        load_op <= '0';

        wait for 10 ns;


        --------------------------------------------------
        -- 10
        -- load_r1 = 1
        --------------------------------------------------

        IR <= "00010000";
        M2 <= '1';
        load_r0 <= '1';

        wait for 10 ns;

        M2 <='0';
        load_r0 <= '0';

        wait for 10 ns;

        
        --------------------------------------------------
        -- C0
        -- load_op = 1
        --------------------------------------------------

        IR <= "11000000";
        load_op <= '1';

        wait for 10 ns;

        load_op <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- 25
        -- M3 = 1
        -- load_r0 = 1
        --------------------------------------------------

        IR <= "00100101";

        M3 <= '1';
        M5 <='1';
        load_r0 <= '1';

        wait for 10 ns;

        M3 <= '0';
        M5 <= '0';
        load_r0 <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- 50
        -- M2 = 1  -> select R1
        -- M4 = 0  -> select R0
        -- M5 = 0  -> select MUX4 output (R0)
        -- M3 = 1  -> select ALU result
        -- load_r0 = 1
        --
        -- Result: R0 <- R1 + R0
        --------------------------------------------------

        IR <= "01010000";

        M2 <= '1';
        M3 <= '1';
        load_r0 <= '1';

        wait for 10 ns;

        M2 <= '0';
        M3 <= '0';
        load_r0 <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- C0
        -- load_op = 1
        --------------------------------------------------

        IR <= "11000000";
        load_op <= '1';

        wait for 10 ns;

        load_op <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- 73
        -- M3 = 1
        --------------------------------------------------
        IR <= "01110011";
        
        M2 <= '1';       
        M3 <= '1';
        M5 <= '1';
        load_r1 <= '1';

        wait for 10 ns;

        load_r1 <= '0';
        M2  <= '0';
        M3  <= '0';
        M5  <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- D0
        -- M2 = 1
        -- load_op = 1
        --------------------------------------------------

        IR <= "11010000";

        M2 <= '1';
        load_op <= '1';

        wait for 10 ns;

        M2 <= '0';
        load_op <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- 90
        --------------------------------------------------

        IR <= "10010000";

        M3 <= '1';
        load_r1 <= '1';

        wait for 10 ns;

        M3 <= '0';
        load_r1 <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- D0
        -- M2 = 1
        -- load_op = 1
        --------------------------------------------------

        IR <= "11010000";

        M2 <= '1';
        load_op <= '1';

        wait for 10 ns;

        M2 <= '0';
        load_op <= '0';

        wait for 10 ns;

        --------------------------------------------------
        -- F0
        --------------------------------------------------

        IR <= "11110000";

        wait for 10 ns;


        --------------------------------------------------
        -- 00
        --------------------------------------------------

        IR <= "00000000";

        wait for 10 ns;

        --------------------------------------------------
        -- END
        --------------------------------------------------

        M1 <= '0';
        M2 <= '0';
        M3 <= '0';
        M4 <= '0';
        M5 <= '0';

        load_r0 <= '0';
        load_r1 <= '0';
        load_op <= '0';

        IR <= "00000000";

        DI <= "0000";

        wait for 20 ns;

        finish;

    end process;

end Behavioral;