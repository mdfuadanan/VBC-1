library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use std.env.all;

entity VBC1_Instruction_Decoder_tb is
end;

architecture Behavioral of VBC1_Instruction_Decoder_tb is

    component VBC1_Instruction_Decoder
        port (
            IR : in std_logic_vector (7 downto 0);
            r0, r1 : in std_logic_vector (3 downto 0);
            IR_7_to_5: out std_logic_vector (7 downto 5);
            IR_3_to_0 : out std_logic_vector(3 downto 0);
            M1,M2,M3,M4,M5,M6,Load_R0,Load_R1,Load_OP,Z1,Z0 : out std_logic
        );
    end component;

    signal IR : std_logic_vector(7 downto 0) := (others => '0');
    signal r0, r1 : std_logic_vector(3 downto 0) := "0000";

    signal IR_7_to_5 : std_logic_vector(7 downto 5);
    signal IR_3_to_0 : std_logic_vector(3 downto 0);

    signal M1,M2,M3,M4,M5,M6 : std_logic;
    signal Load_R0, Load_R1, Load_OP : std_logic;
    signal Z1, Z0 : std_logic;

begin

    --------------------------------------------------
    -- DUT
    --------------------------------------------------
    DUT: VBC1_Instruction_Decoder
        port map(
            IR => IR,
            r0 => r0,
            r1 => r1,
            IR_7_to_5 => IR_7_to_5,
            IR_3_to_0 => IR_3_to_0,
            M1 => M1,
            M2 => M2,
            M3 => M3,
            M4 => M4,
            M5 => M5,
            M6 => M6,
            Load_R0 => Load_R0,
            Load_R1 => Load_R1,
            Load_OP => Load_OP,
            Z1 => Z1,
            Z0 => Z0
        );

    --------------------------------------------------
    -- TEST PROCESS
    --------------------------------------------------
    process
    begin

        --------------------------------------------------
        -- Initialize registers
        --------------------------------------------------
        r0 <= "0011";  -- non-zero
        r1 <= "0101";  -- non-zero
        wait for 10 ns;

        --------------------------------------------------
        -- B0  (IN)
        --------------------------------------------------
        IR <= "10110000";
        wait for 10 ns;

        --------------------------------------------------
        -- D0  (OUT)
        --------------------------------------------------
        IR <= "11010000";
        wait for 10 ns;

        --------------------------------------------------
        -- 23 (LOADI)
        --------------------------------------------------
        IR <= "00100011";
        wait for 10 ns;

        --------------------------------------------------
        -- C0 (OUT)
        --------------------------------------------------
        IR <= "11000000";
        wait for 10 ns;

        --------------------------------------------------
        -- 10 (MOV)
        --------------------------------------------------
        IR <= "00010000";
        wait for 10 ns;

        --------------------------------------------------
        -- C0
        --------------------------------------------------
        IR <= "11000000";
        wait for 10 ns;

        --------------------------------------------------
        -- 25
        --------------------------------------------------
        IR <= "00100101";
        wait for 10 ns;

        --------------------------------------------------
        -- 50 (ADD)
        --------------------------------------------------
        IR <= "01010000";
        wait for 10 ns;

        --------------------------------------------------
        -- C0
        --------------------------------------------------
        IR <= "11000000";
        wait for 10 ns;

        --------------------------------------------------
        -- 73 (ADDI)
        --------------------------------------------------
        IR <= "01110011";
        wait for 10 ns;

        --------------------------------------------------
        -- D0
        --------------------------------------------------
        IR <= "11010000";
        wait for 10 ns;

        --------------------------------------------------
        -- 90 (SHIFT)
        --------------------------------------------------
        IR <= "10010000";
        wait for 10 ns;

        --------------------------------------------------
        -- D0
        --------------------------------------------------
        IR <= "11010000";
        wait for 10 ns;

        --------------------------------------------------
        -- F0 (JNZ)
        --------------------------------------------------
        IR <= "11110000";
        wait for 10 ns;

        --------------------------------------------------
        -- 00 (MOV R0,R0)
        --------------------------------------------------
        IR <= "00000000";
        wait for 10 ns;

        --------------------------------------------------
        -- END
        --------------------------------------------------
        wait for 20 ns;
        finish;

    end process;

end Behavioral;